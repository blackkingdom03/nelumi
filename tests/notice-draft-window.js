const assert=require('node:assert/strict'),path=require('node:path');
const {app,BrowserWindow}=require('electron');
const profile=path.join(__dirname,'..',`.test-profile-notice-draft-${Date.now()}`);
app.setPath('userData',profile);app.setPath('sessionData',profile);
app.whenReady().then(async()=>{
 const win=new BrowserWindow({show:false,width:1100,height:850,webPreferences:{contextIsolation:true,nodeIntegration:false,sandbox:true}});
 await win.loadFile(path.join(path.resolve(process.argv[2] || path.join(__dirname,'..')),'src/renderer/index.html'));
 win.webContents.setBackgroundThrottling(false);
 const js=code=>win.webContents.executeJavaScript(code);
 const until=async code=>{for(let i=0;i<100;i++){if(await js(code))return;await new Promise(r=>setTimeout(r,30));}throw Error(code);};
 const paste=async text=>js(`document.querySelector('#noticeInput').value=${JSON.stringify(text)};document.querySelector('#noticeInput').dispatchEvent(new Event('input'));document.querySelector('#noticeForm').requestSubmit()`);
 const save=()=>js("document.querySelector('#eventForm').requestSubmit()");
 await until("typeof state!=='undefined' && state.settings.theme");
 const text='每年11月8日小林生日，提前一周和一天提醒我，地点：海棠餐厅';
 await paste(text);await until("document.querySelector('#eventDialog').open");
 assert.equal(await js('state.events.length'),0,'draft cannot save before confirmation');
 assert.equal(await js("document.querySelector('#eventRepeat').value"),'yearly');
 assert.deepEqual(await js("[...document.querySelectorAll('#eventReminderOptions input:checked')].map(x=>+x.value).sort((a,b)=>a-b)"),[1440,10080]);
 assert.equal(await js("document.querySelector('#eventLocation').value"),'海棠餐厅');
 await js("document.querySelector('#eventDialog [data-close-dialog]').click()");
 assert.equal(await js('state.events.length'),0);
 assert.equal(await js("document.querySelector('#noticeInput').value"),text);
 await paste(text);await until("document.querySelector('#eventDialog').open");
 await js("document.querySelector('#eventTitle').value='小林生日聚餐';document.querySelector('#eventLocation').value='海棠餐厅二楼';window.writer=window.deskcal.saveEvents;window.deskcal.saveEvents=async()=>{throw Error('模拟磁盘失败')};void 0");
 await save();await until("document.querySelector('#notebookStatus').textContent.includes('模拟磁盘失败')");
 assert.equal(await js('state.events.length'),0);assert.equal(await js("document.querySelector('#eventDialog').open"),true);
 await js("window.deskcal.saveEvents=window.writer;void 0");await save();
 await until("!document.querySelector('#eventDialog').open && state.events.length===1");
 const created=await js('state.events[0]');
 assert.equal(created.title,'小林生日聚餐');assert.equal(created.location,'海棠餐厅二楼');assert.equal(created.sourceText,text);
 assert.equal(created.recurrence.frequency,'yearly');assert.deepEqual(created.reminders.sort((a,b)=>a-b),[1440,10080]);
 assert.equal(await js("DeskCalCore.occursOn(state.events[0],DeskCalCore.parseDate('2027-11-08'))"),true);
 await js("document.querySelector('#undoNoticeButton').click()");await until('activeEvents().length===0');
 await js("document.querySelector('#redoNoticeButton').click()");await until('activeEvents().length===1');
 await js(`openEventDialog(${JSON.stringify(created.id)},'2027-11-08')`);
 assert.equal(await js("document.querySelector('#eventReminderOptions input[value=\"10080\"]').checked"),true);
 await js("document.querySelector('#eventDialog').close()");
 await paste('普通通知：明天整理资料');await until('activeEvents().length===2');
 assert.equal(await js("document.querySelector('#eventDialog').open"),false);
 // All range endpoints are reviewed; no partial writes when cancelling halfway.
 await paste('活动：10月23日-11月23日，提前一天提醒');await until("document.querySelector('#eventDialog').open");
 await save();await until("document.querySelector('#eventTitle').value.endsWith('结束')");
 assert.equal(await js('activeEvents().length'),2);
 await js("document.querySelector('#eventDialog').close()");assert.equal(await js('activeEvents().length'),2);
 await paste('活动：10月23日-11月23日，提前一天提醒');await until("document.querySelector('#eventDialog').open");
 await save();await until("document.querySelector('#eventTitle').value.endsWith('结束')");await save();
 await until('activeEvents().length===4');
 await paste('农历8月15日妈妈生日，每年提醒');await until("document.querySelector('#eventDialog').open");
 assert.equal(await js("document.querySelector('#eventDate').value"),'2026-09-25');
 assert.equal(await js("document.querySelector('#eventDateCalendar').value"),'lunar');
 assert.equal(await js("document.querySelector('#eventRepeat').value"),'yearly');
 assert.equal(await js("document.querySelector('#eventForm').checkValidity()"),true);
 await save();await until('activeEvents().length===5');
 const lunar=await js('activeEvents().at(-1)');
 assert.deepEqual(lunar.lunarDate,{month:8,day:15,leap:false});
 assert.equal(await js("DeskCalCore.occursOn(activeEvents().at(-1),DeskCalCore.parseDate('2027-09-15'))"),true);
 await js(`openEventDialog(${JSON.stringify(lunar.id)},'2027-09-15')`);
 assert.equal(await js("document.querySelector('#eventLunarYear').value"),'2027');
 assert.equal(await js("document.querySelector('#eventLunarDay').value"),'15');
 await js("document.querySelector('#eventEditScope').value='series';document.querySelector('#eventLocation').value='全家聚餐'");
 await save();await until("!document.querySelector('#eventDialog').open");
 assert.equal(await js(`state.events.find(e=>e.id===${JSON.stringify(lunar.id)}).date`),'2026-09-25','editing a future occurrence must not shift the whole lunar series');
 await paste('农历闰六月初一小林生日，每年提醒');await until("document.querySelector('#eventDialog').open");
 assert.equal(await js("document.querySelector('#eventDate').value"),'');
 assert.equal(await js("document.querySelector('#eventForm').checkValidity()"),false);
 await js("document.querySelector('#eventLunarYear').value='2025';document.querySelector('#eventLunarYear').dispatchEvent(new Event('change'))");
 assert.equal(await js("document.querySelector('#eventDate').value"),'2025-07-25');
 await save();await until('activeEvents().length===6');
 await js("state.viewDate=DeskCalCore.parseDate('2026-10-01');render()");
 assert.match(await js("document.querySelector('#lunarYearNotice').textContent"),/未自动安排/);
 await paste('农历八月十五妈妈生日，每年提醒');await until("document.querySelector('#eventDialog').open");
 await js("document.querySelector('#eventDateCalendar').value='solar';document.querySelector('#eventDateCalendar').dispatchEvent(new Event('change'));document.querySelector('#eventDate').value='2026-08-15'");
 await save();await until('activeEvents().length===7');
 assert.equal(await js('activeEvents().at(-1).lunarDate'),null);
 console.log('Birthday editor, cancel, failure/retry, persistence, recurrence, undo/redo, range review, solar/lunar switching, leap validation and series editing passed.');
 app.quit();
}).catch(error=>{console.error(error);app.exit(1)});
